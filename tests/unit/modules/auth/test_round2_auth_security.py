class TestMagicLinkDBGuards:
    """Tests for A2-12: Magic link DB used_at and expires_at guards."""

    @pytest.mark.asyncio
    async def test_verify_rejects_already_used_db_link(self) -> None:
        """verify_magic_link rejects token if DB record shows it was already used."""
        mock_db = AsyncMock()
        mock_redis = AsyncMock()

        service = MagicLinkService(db=mock_db, redis=mock_redis)

        # Redis peek returns valid data
        mock_manager = AsyncMock()
        mock_manager.peek = AsyncMock(return_value={"email": "u@test.com", "action": "login"})
        mock_manager.consume = AsyncMock(return_value={"email": "u@test.com"})
        service._get_magic_link_manager = MagicMock(return_value=mock_manager)

        # But DB link shows it was already used at 5 minutes ago
        mock_db_link = MagicMock()
        mock_db_link.used_at = datetime.now(UTC) - timedelta(minutes=5)

        with patch(
            "src.app.modules.auth.crud.get_magic_link_by_token",
            new_callable=AsyncMock,
            return_value=mock_db_link,
        ):
            with pytest.raises(MagicLinkAlreadyUsedError, match="already used"):
                await service.verify_magic_link("valid-token", "127.0.0.1")

    @pytest.mark.asyncio
    async def test_verify_rejects_expired_db_link(self) -> None:
        """verify_magic_link rejects token if DB record shows expires_at has passed."""
        mock_db = AsyncMock()
        mock_redis = AsyncMock()

        service = MagicLinkService(db=mock_db, redis=mock_redis)

        mock_manager = AsyncMock()
        mock_manager.peek = AsyncMock(return_value={"email": "u@test.com", "action": "login"})
        service._get_magic_link_manager = MagicMock(return_value=mock_manager)

        mock_db_link = MagicMock()
        mock_db_link.used_at = None
        mock_db_link.expires_at = datetime.now(UTC) - timedelta(minutes=1)

        with patch(
            "src.app.modules.auth.crud.get_magic_link_by_token",
            new_callable=AsyncMock,
            return_value=mock_db_link,
        ):
            with pytest.raises(InvalidMagicLinkError, match="expired"):
                await service.verify_magic_link("valid-token", "127.0.0.1")


class TestTokenIssuerClaimProtection:
    """Tests for A2-02: TokenIssuer protects core JWT claims from extra_claims overwrite."""

    def test_reserved_claims_cannot_be_overwritten(self) -> None:
        """extra_claims cannot overwrite sub, tenant_id, tier_id, or token_version."""
        token_data = TokenIssuer.build_token_data(
            subject="legitimate_user",
            user={"id": 1, "tenant_id": uuid4(), "tier_id": 1, "token_version": 2},
        )
        original_sub = token_data["sub"]
        original_tv = token_data["token_version"]

        RESERVED_CLAIMS = frozenset({"sub", "tenant_id", "tier_id", "tier_name", "token_version"})
        malicious_extra = {
            "sub": "admin",
            "token_version": 999,
            "custom_claim": "safe_value",
        }
        safe_extra = {k: v for k, v in malicious_extra.items() if k not in RESERVED_CLAIMS}
        token_data.update(safe_extra)

        assert token_data["sub"] == original_sub
        assert token_data["token_version"] == original_tv
        assert token_data["custom_claim"] == "safe_value"
