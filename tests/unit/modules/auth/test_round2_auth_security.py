class TestTOTPReplayProtection:
    """Tests for A2-04: single-use TOTP token replay protection."""

    @pytest.mark.asyncio
    async def test_totp_token_replay_rejected(self) -> None:
        """Submitting the same valid TOTP code twice within the window raises BadRequestException."""
        import pyotp

        service = MFAService()
        secret = pyotp.random_base32()
        encrypted_secret = await service._encrypt_secret(secret)
        totp = pyotp.TOTP(secret)
        valid_code = totp.now()

        mock_db = AsyncMock()
        mock_method = MagicMock()
        mock_method.id = 1
        mock_method.user_id = 42
        mock_method.secret = encrypted_secret
        mock_db.get = AsyncMock(return_value=mock_method)

        mock_redis = AsyncMock()
        # First attempt: setnx returns True (fresh)
        # Second attempt: setnx returns None (already used)
        mock_redis.set.side_effect = [True, None]

        req = MFAVerifyRequest(totp_token=valid_code)

        with (
            patch("src.app.modules.auth.services.mfa.get_redis", return_value=mock_redis),
            patch(
                "src.app.modules.auth.services.mfa.crud_mfa_methods.get",
                new_callable=AsyncMock,
                return_value={"id": 1, "secret": encrypted_secret},
            ),
            patch.object(service, "_check_mfa_lockout", new_callable=AsyncMock),
            patch.object(service, "_reset_mfa_lockout", new_callable=AsyncMock),
            patch("src.app.modules.auth.services.mfa.audit", new_callable=AsyncMock),
        ):
            # First verification succeeds
            result1 = await service.verify_totp_token(42, req, mock_db, prevent_replay=True)
            assert result1["valid"] is True

            # Second verification with same code fails with replay error
            with pytest.raises(ValidationError, match="already been used"):
                await service.verify_totp_token(42, req, mock_db, prevent_replay=True)


class TestMFASetupTokenBinding:
    """Tests for A2-06: setup_token bound to user_id."""

    @pytest.mark.asyncio
    async def test_setup_token_wrong_user_rejected(self) -> None:
        """User B cannot enable MFA using a setup_token generated by User A."""
        service = MFAService()
        mock_db = AsyncMock()

        # Token was created for user 100
        setup_token = "token-for-user-100"
        secret = "JBSWY3DPEHPK3PXP"
        stored_val = f"100:{secret}".encode()

        mock_redis = AsyncMock()
        mock_redis.get.return_value = stored_val

        # User 200 attempts to enable MFA with user 100's setup token
        req = MFAEnableRequest(setup_token=setup_token, totp_token="123456", password="correct-horse")

        with (
            patch("src.app.modules.auth.services.mfa.get_redis", return_value=mock_redis),
            patch("src.app.modules.auth.services.mfa.crud_mfa_methods.get", new_callable=AsyncMock, return_value=None),
        ):
            with pytest.raises(ValidationError, match="does not belong to the current user"):
                await service.enable_mfa(200, req, mock_db)


