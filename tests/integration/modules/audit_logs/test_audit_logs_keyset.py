"""Keyset pagination over real rows (Phase 3.2).

The unit tests pin the STATEMENT; these pin the SEMANTICS that only a real
result set can show: equal ``created_at`` ties, the strict seek (no row
repeated, none skipped), the last page, and tenant isolation.
"""

from datetime import UTC, datetime, timedelta
from uuid import uuid4

import pytest

from src.app.modules.audit_logs.models import AuditLog
from src.app.modules.audit_logs.service import AuditLogService
from src.app.modules.tenants.models import Tenant

BASE = datetime(2026, 1, 1, 12, 0, 0, tzinfo=UTC)


async def _tenant(db_session) -> Tenant:
    tenant = Tenant(name="Keyset Tenant", slug=f"keyset-{uuid4().hex[:12]}", is_active=True)
    db_session.add(tenant)
    await db_session.commit()
    await db_session.refresh(tenant)
    return tenant


async def _add_log(db_session, tenant_id, created_at: datetime, action: str = "test.action") -> AuditLog:
    # ``created_at`` is ``init=False`` on the model (DB-generated by default), so
    # it is assigned after construction to pin the value this test needs.
    log = AuditLog(
        tenant_id=tenant_id,
        action=action,
        entity_type="test",
        entity_id=None,
        details={},
        user_id=None,
        ip_address=None,
        user_agent=None,
    )
    log.created_at = created_at
    db_session.add(log)
    await db_session.commit()
    await db_session.refresh(log)
    return log


async def _walk(service: AuditLogService, tenant_id, limit: int) -> list:
    """Follow ``next_cursor`` to the end and return every row, in order."""
    seen: list = []
    cursor: str | None = None
    for _ in range(20):  # hard stop: a paging loop must not hang the suite
        page = await service.query_logs_keyset(tenant_id, cursor=cursor, limit=limit)
        seen.extend(page["items"])
        if not page["has_next"]:
            assert page["next_cursor"] is None
            return seen
        cursor = page["next_cursor"]
    raise AssertionError("keyset pagination did not terminate")


class TestKeysetOverRealRows:
    @pytest.mark.asyncio
    async def test_every_row_is_served_exactly_once_across_pages(self, db_session) -> None:
        tenant = await _tenant(db_session)
        # Five rows sharing one timestamp is the case a bare ``created_at``
        # cursor gets wrong: the strict id tie-breaker is what separates them.
        for index in range(5):
            await _add_log(db_session, tenant.id, BASE, action=f"tie.{index}")
        await _add_log(db_session, tenant.id, BASE - timedelta(seconds=1), action="older")

        service = AuditLogService(db_session)
        walked = await _walk(service, tenant.id, limit=2)

        assert len(walked) == 6
        assert len({log.id for log in walked}) == 6, "a row was served twice"
        assert [log.action for log in walked][-1] == "older", "ordering is created_at DESC"
        # Descending by id inside the tie, so the page order is deterministic.
        tie_ids = [log.id for log in walked if log.action.startswith("tie.")]
        assert tie_ids == sorted(tie_ids, reverse=True)

    @pytest.mark.asyncio
    async def test_the_last_page_reports_no_cursor(self, db_session) -> None:
        tenant = await _tenant(db_session)
        for _ in range(3):
            await _add_log(db_session, tenant.id, BASE)

        service = AuditLogService(db_session)
        first = await service.query_logs_keyset(tenant.id, limit=2)
        second = await service.query_logs_keyset(tenant.id, cursor=first["next_cursor"], limit=2)

        assert first["has_next"] is True
        assert len(first["items"]) == 2
        assert len(second["items"]) == 1, "the short page is the end of the listing"
        assert second["has_next"] is False
        assert second["next_cursor"] is None

    @pytest.mark.asyncio
    async def test_a_full_page_with_no_next_row_still_offers_a_cursor(self, db_session) -> None:
        """Exactly ``limit`` rows: "full" is not "more", and the next hop is empty.

        This is the documented contract (``next_cursor`` iff the page is full),
        so the client makes ONE extra request that returns nothing rather than
        the server paying a look-ahead query on every page.
        """
        tenant = await _tenant(db_session)
        for _ in range(2):
            await _add_log(db_session, tenant.id, BASE)

        service = AuditLogService(db_session)
        first = await service.query_logs_keyset(tenant.id, limit=2)
        assert first["has_next"] is True

        empty = await service.query_logs_keyset(tenant.id, cursor=first["next_cursor"], limit=2)
        assert empty == {"items": [], "next_cursor": None, "has_next": False, "limit": 2}

    @pytest.mark.asyncio
    async def test_an_empty_tenant_gets_an_empty_page(self, db_session) -> None:
        tenant = await _tenant(db_session)

        page = await AuditLogService(db_session).query_logs_keyset(tenant.id, limit=10)

        assert page["items"] == []
        assert page["has_next"] is False

    @pytest.mark.asyncio
    async def test_another_tenants_rows_are_never_served(self, db_session) -> None:
        tenant_a = await _tenant(db_session)
        tenant_b = await _tenant(db_session)
        await _add_log(db_session, tenant_a.id, BASE, action="a.action")
        await _add_log(db_session, tenant_b.id, BASE - timedelta(days=1), action="b.action")

        service = AuditLogService(db_session)
        page_a = await service.query_logs_keyset(tenant_a.id, limit=10)
        page_b = await service.query_logs_keyset(tenant_b.id, limit=10)

        assert [log.action for log in page_a["items"]] == ["a.action"]
        assert [log.action for log in page_b["items"]] == ["b.action"]

    @pytest.mark.asyncio
    async def test_filters_apply_to_every_page(self, db_session) -> None:
        tenant = await _tenant(db_session)
        for _ in range(3):
            await _add_log(db_session, tenant.id, BASE, action="keep.me")
        await _add_log(db_session, tenant.id, BASE, action="drop.me")

        service = AuditLogService(db_session)
        walked = await _walk(service, tenant.id, limit=1)  # unfiltered sanity
        assert len(walked) == 4

        filtered = await service.query_logs_keyset(tenant.id, action="keep.me", limit=2)
        assert len(filtered["items"]) == 2
        second = await service.query_logs_keyset(
            tenant.id, action="keep.me", cursor=filtered["next_cursor"], limit=2
        )
        assert [log.action for log in second["items"]] == ["keep.me"]
        assert second["has_next"] is False
